#!/usr/bin/env node
'use strict';
// Writes ai-marks-data.js: the AI makers' monochrome marks, taken from @lobehub/icons-static-svg (MIT, © LobeHub;
// https://github.com/lobehub/lobe-icons), as inner SVG markup on a 24 × 24 box in currentColor. The marks name the makers
// whose models a page lists (nominative use, as every model leaderboard does); each remains its owner's trademark.
//   node scripts/build-ai-marks.js <path to an unpacked @lobehub/icons-static-svg package>
const fs = require('fs');
const path = require('path');

const PKG = process.argv[2];
if (!PKG) { console.error('usage: node scripts/build-ai-marks.js <unpacked @lobehub/icons-static-svg>'); process.exit(1); }
const pkg = JSON.parse(fs.readFileSync(path.join(PKG, 'package.json'), 'utf8'));
// Our family key → LobeHub's file (the mono drawing).
const FILES = {
    OpenAI: 'openai', Anthropic: 'claude', Google: 'gemini', Gemma: 'gemma', Meta: 'meta', DeepSeek: 'deepseek', Qwen: 'qwen',
    Mistral: 'mistral', Kimi: 'kimi', GLM: 'zhipu', MiniMax: 'minimax', Microsoft: 'microsoft', xAI: 'grok', NVIDIA: 'nvidia',
    Cohere: 'cohere', Perplexity: 'perplexity',
};
const out = {};
for (const [key, file] of Object.entries(FILES)) {
    const svg = fs.readFileSync(path.join(PKG, 'icons', `${file}.svg`), 'utf8');
    const vb = /viewBox="([^"]+)"/.exec(svg);
    if (!vb || vb[1] !== '0 0 24 24') throw new Error(`${file}: viewBox ${vb && vb[1]}, expected 0 0 24 24`);
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>[\s\S]*?<\/title>/, '').trim();
    if (/<script|on[a-z]+=|href=|<image|<foreignObject/i.test(inner)) throw new Error(`${file}: unexpected markup`);
    out[key] = inner;
}
const header = `'use strict';\n// Generated by scripts/build-ai-marks.js from @lobehub/icons-static-svg ${pkg.version} (MIT, © LobeHub,\n// https://github.com/lobehub/lobe-icons). Do not edit: re-run the script. Each mark is its owner's trademark, used here to\n// name the maker of a model.\n`;
fs.writeFileSync(path.join(__dirname, '..', 'ai-marks-data.js'), `${header}module.exports = ${JSON.stringify(out, null, 1)};\n`);
console.log('ai-marks-data.js:', Object.keys(out).length, 'marks from', pkg.version);
