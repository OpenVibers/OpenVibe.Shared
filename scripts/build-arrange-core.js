#!/usr/bin/env node
'use strict';
/**
 * Writes ov-arrange-core.js: openvibe-sdk/ui-layout for the browser, as one classic script that sets
 * window.OVArrangeCore. One implementation of the rules, not two: this copies the SDK's own src/ui-layout.js
 * unchanged but for the name of module.exports, and records the SDK version and the file's SHA-256.
 * test/ov-arrange-core.test.js checks the file is current and runs the SDK's own cases through it.
 *
 *   node scripts/build-arrange-core.js [<path to openvibe-sdk>]     # default: node_modules/openvibe-sdk
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');

function build(sdkDir = path.join(ROOT, 'node_modules', 'openvibe-sdk')) {
    const pkg = JSON.parse(fs.readFileSync(path.join(sdkDir, 'package.json'), 'utf8'));
    const file = path.join(sdkDir, 'src', 'ui-layout.js');
    if (!fs.existsSync(file)) throw new Error(`openvibe-sdk ${pkg.version} has no src/ui-layout.js: release the SDK with ui-layout first`);
    const src = fs.readFileSync(file, 'utf8');
    const bad = [...src.matchAll(/require\((['"])([^'"]+)\1\)/g)].map((m) => m[2]);
    if (bad.length) throw new Error(`src/ui-layout.js requires ${bad.join(', ')}: the browser build takes a self-contained module`);
    const hash = crypto.createHash('sha256').update(src).digest('hex').slice(0, 16);
    // The one change: module.exports takes the browser's own name, so the browser file says no module.
    const body = src.replace(/\bmodule\.exports\b/g, '__ovArrangeCoreModule.exports');
    return `/* Generated by scripts/build-arrange-core.js from openvibe-sdk ${pkg.version} (src/ui-layout.js). Do not edit:
 * change the SDK, release it, bump the pin, and run the script. The SDK's file, unchanged but for the name of
 * module.exports:
 *   ui-layout.js ${hash}
 */
(function (root) {
    'use strict';
    if (!root || root.OVArrangeCore) return;
    const __ovArrangeCoreModule = { exports: {} };
${body}
    root.OVArrangeCore = __ovArrangeCoreModule.exports;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
}

if (require.main === module) {
    const out = build(process.argv[2]);
    fs.writeFileSync(path.join(ROOT, 'ov-arrange-core.js'), out);
    console.log('ov-arrange-core.js written');
}
module.exports = { build };
