#!/usr/bin/env node
'use strict';
/**
 * Regenerates the icon block inside navbar.js from nav-icons.js.
 *
 * navbar.js is on every page's first load, so it carries only the glyphs it draws by itself (every
 * navIcon('fa-…') literal in its own source: the account menu, the admin link, the wallet chip).
 * Every other glyph stays in nav-icons.js, which the navbar fetches after first paint the first time
 * a site's link, chip or menu row names one; the block keeps their widths so the empty slot is
 * already the right size, and the file's content hash so the fetch is cacheable forever.
 *
 *   node scripts/build-navbar-icons.js          # rewrite
 *   node scripts/build-navbar-icons.js --check  # exit 1 if stale
 *
 * Every entry is an OpenVibe glyph (openvibe-shared/glyphs): a name the glyphs do not cover is an error here, never
 * a drawing from another set (4.231.0: the last Font Awesome outlines, the ring icons' solids, went).
 *
 * 4.71.0 (the owner, 2026-11-01: one hand in the bar): every entry of nav-icons.js is [0, line, solid], the set's own
 * drawings on a 24-unit grid. This script rewrites those entries first, then the block, then the ring icons' solids in
 * ov-icons.js (RING_SOLIDS: each product's solid is the glyph that stands for it).
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const NAVBAR = path.join(ROOT, 'navbar.js');
const ICONS = path.join(ROOT, 'nav-icons.js');
const OV_ICONS = path.join(ROOT, 'ov-icons.js');
const glyphs = require('../glyphs');
const q = (str) => String(str).replace(/\\/g, '\\\\').replace(/'/g, "\\'");

/**
 * A path with its coordinates on a half-unit grid, for the navbar's own copy.
 *
 * The bar draws these at 15-20 px, where half a unit of a 24-box is a third of a pixel — and the
 * navbar's block is on every page's first load, so the shorter numbers are worth the tenth of a
 * pixel. The drawings in glyphs.js keep their tenths: they are the ones the sets' own measurements
 * are made against. An arc's flags and its rotation are not coordinates and are left alone.
 */
const coarse = (d) => d.replace(/( d=")([^"]*)(")/g, (m, a, body, b) => {
    let out = '', cmd = '', n = 0, lastNumber = false;
    for (const tok of body.match(/[AaCcSsQqTtLlHhVvMmZz]|-?\d*\.?\d+(?:e[-+]?\d+)?/g) || []) {
        if (/[A-Za-z]/.test(tok)) { out += tok; cmd = tok; n = 0; lastNumber = false; continue; }
        // An arc's numbers come in groups of seven — rx ry rotation large-arc sweep x y — and the
        // rotation and the two flags are not coordinates.
        const keep = /[Aa]/.test(cmd) && (n % 7) >= 2 && (n % 7) <= 4;
        n++;
        const value = keep ? tok : (Object.is(Math.round(Number(tok) * 2) / 2, -0) ? '0' : (Math.round(Number(tok) * 2) / 2).toString());
        if (lastNumber && value[0] !== '-') out += ' ';
        out += value;
        lastNumber = true;
    }
    return a + out + b;
});

/** nav-icons.js with every entry drawn from the glyphs: [0, line, solid]. A name they do not cover is an error. */
function upgraded(text) {
    const missing = [];
    const out = text.replace(/^( {8}'(fa-[a-z0-9-]+)': )\[.*\],$/gm, (line, head, name) => {
        const g = glyphs.fromFa(name);
        if (!g) { missing.push(name); return line; }
        return `${head}[0, '${q(glyphs.path(g))}', '${q(glyphs.solid(g) || '')}'],`;
    });
    if (missing.length) throw new Error(`nav-icons.js names icons the OpenVibe glyphs do not have: ${missing.join(', ')} (draw them in glyphs.js, or map the name in glyphs.FA)`);
    return out;
}

// The ring icons' solids (ov-icons.js): each product's solid is the glyph that stands for it, the same drawing the
// glyph font and ov-glyphs.js show. A product without one here keeps its line drawing at every size.
const RING_SOLIDS = { network: 'nodes', live: 'live', tools: 'wrench', media: 'film', games: 'game', community: 'members', chat: 'chat', domains: 'globe', bench: 'flag' };
const RING_BEGIN = '    // BEGIN generated ring solids (scripts/build-navbar-icons.js from glyphs.js)';
const RING_END = '    // END generated ring solids';
function ringSolids(text) {
    const a = text.indexOf(RING_BEGIN);
    const b = text.indexOf(RING_END, a);
    if (a < 0 || b < 0) throw new Error('ov-icons.js: generated ring solids block not found');
    const rows = Object.entries(RING_SOLIDS).map(([k, g]) => {
        const d = glyphs.solid(g);
        if (!d) throw new Error(`ring solid ${k}: the glyph ${g} has no solid drawing`);
        return `        // ${k}: the glyph ${g}\n        ${k}: '${q(d)}',`;
    });
    return text.slice(0, a) + [RING_BEGIN, '    // The solid drawing of the glyph that stands for each product (24-unit grid, openvibe-shared/glyphs).', '    const SOLID = {', ...rows, '    };', ''].join('\n') + text.slice(b);
}
const BEGIN_PREFIX = '    // BEGIN generated';
const BEGIN = '    // BEGIN generated by scripts/build-navbar-icons.js from nav-icons.js; do not edit by hand';
const END = '    // END generated';

function block(src) {
    const a = src.indexOf(BEGIN_PREFIX);
    const b = src.indexOf(END, a);
    if (a < 0 || b < 0) throw new Error('navbar.js: generated icon block not found');
    return { a, b: b + END.length };
}

/** Glyph names navbar.js asks for itself, outside the generated block. */
function ownIcons(src) {
    const { a, b } = block(src);
    const rest = src.slice(0, a) + src.slice(b);
    return [...new Set([...rest.matchAll(/navIcon\('(fa-[a-z0-9-]+)'\)/g)].map((m) => m[1]))];
}

function render(src, iconsText) {
    const buf = Buffer.from(iconsText);
    const mod = { exports: {} };
    new Function('module', iconsText)(mod);   // the file as it will be written, not the one on disk
    const all = mod.exports;
    const own = ownIcons(src);
    const missing = own.filter((n) => !all[n]);
    if (missing.length) throw new Error(`navbar.js draws icons nav-icons.js does not have: ${missing.join(', ')}`);
    const byWidth = {};
    for (const [name, [w]] of Object.entries(all)) {
        if (w !== 0) throw new Error(`nav-icons.js: ${name} is not an OpenVibe glyph`);
        if (own.includes(name)) continue;
        (byWidth[w] = byWidth[w] || []).push(name);
    }
    const rev = crypto.createHash('sha256').update(buf).digest('hex').slice(0, 12);
    return [
        BEGIN,
        '    // The glyphs the navbar draws itself: [0, line, solid], OpenVibe glyphs on a 24-unit grid. The rest of the set is nav-icons.js.',
        '    const NAV_ICONS = {',
        ...Object.keys(all).filter((n) => own.includes(n)).map((n) => `        '${n}': [0, '${q(coarse(all[n][1]))}', '${q(coarse(all[n][2] || ''))}'],`),
        '    };',
        '    // Every other glyph in nav-icons.js, by width (0: a 24-unit OpenVibe glyph), so its slot has its size before the path arrives.',
        '    const NAV_ICONS_LAZY = {',
        ...Object.keys(byWidth).map((w) => `        ${w}: '${byWidth[w].join(' ')}',`),
        '    };',
        `    const NAV_ICONS_REV = '${rev}';   // sha256(nav-icons.js), first 12 hex: its ?v= (cacheable forever)`,
        END,
    ].join('\n');
}

const check = process.argv.includes('--check');
const iconsWas = fs.readFileSync(ICONS, 'utf8');
const iconsNow = upgraded(iconsWas);
const oviWas = fs.readFileSync(OV_ICONS, 'utf8');
const oviNow = ringSolids(oviWas);
const src = fs.readFileSync(NAVBAR, 'utf8');
const { a, b } = block(src);
const next = src.slice(0, a) + render(src, iconsNow) + src.slice(b);
if (check) {
    if (iconsNow !== iconsWas) { console.error('nav-icons.js is not the glyphs\' drawings: run node scripts/build-navbar-icons.js'); process.exit(1); }
    if (oviNow !== oviWas) { console.error('ov-icons.js ring solids are stale: run node scripts/build-navbar-icons.js'); process.exit(1); }
    if (next !== src) { console.error('navbar.js icon block is stale: run node scripts/build-navbar-icons.js'); process.exit(1); }
    console.log('navbar.js icon block is up to date');
} else if (next !== src || iconsNow !== iconsWas || oviNow !== oviWas) {
    if (iconsNow !== iconsWas) fs.writeFileSync(ICONS, iconsNow);
    if (oviNow !== oviWas) fs.writeFileSync(OV_ICONS, oviNow);
    fs.writeFileSync(NAVBAR, next);
    console.log(`navbar.js: ${ownIcons(src).length} built-in glyphs, the rest load from nav-icons.js`);
} else {
    console.log('navbar.js icon block already up to date');
}
