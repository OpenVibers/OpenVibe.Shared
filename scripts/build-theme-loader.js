#!/usr/bin/env node
'use strict';
/**
 * Regenerates the built-in theme map inside theme-loader.js from builtin-themes.js.
 *
 * theme-loader.js runs in the browser before the first paint and cannot require() the catalog, so
 * it carries a copy. That copy used to be maintained by hand and drifted. Now it is generated:
 *
 *   node scripts/build-theme-loader.js          # rewrite
 *   node scripts/build-theme-loader.js --check  # exit 1 if stale
 *
 * The seasons (builtin-themes.js SEASONS) come along as SEASONS: which theme is the default when (dark and light), and
 * PAIRS / MODES: each theme's other half and its own mode, for the Light / Dark / Auto switch.
 *
 * Every entry carries the FULL variable set (the theme's own values over the default theme's), so
 * switching themes replaces every token — a theme that does not name --success no longer keeps the
 * previous theme's --success on <html>. They are written as rows of values against one list of names and expanded
 * at load (the names were most of the file).
 */
const fs = require('fs');
const path = require('path');
const { BUILTIN_THEMES, DEFAULT_VARS, SEASONS } = require('../builtin-themes');

const LOADER = path.join(__dirname, '..', 'theme-loader.js');
const BEGIN = '    // THEMES:BEGIN — generated by scripts/build-theme-loader.js from builtin-themes.js; do not edit by hand';
const END = '    // THEMES:END';

function render() {
    // One list of token names and, per theme, its values in that order: the names were most of the file (50 themes × 45
    // names), and every site loads it before first paint. '' means the default theme's value. The loader expands each row
    // into the FULL set at load, so switching themes still replaces every token.
    const keys = [...new Set([...Object.keys(DEFAULT_VARS), ...BUILTIN_THEMES.flatMap((t) => Object.keys(t.variables))])];
    const q = (v) => `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
    const rows = BUILTIN_THEMES.map((t) => {
        const vars = { ...DEFAULT_VARS, ...t.variables };
        const vals = keys.map((k) => (t.id !== 'vibe' && vars[k] === DEFAULT_VARS[k] ? "''" : q(vars[k] == null ? '' : vars[k])));
        while (vals.length && vals[vals.length - 1] === "''") vals.pop();
        return `        '${t.id}': [${vals.join(',')}],`;
    });
    const seasons = SEASONS.map((s) => `        { id: '${s.id}', name: '${s.name.replace(/'/g, "\\'")}', theme: '${s.theme}', light: '${s.light}', from: '${s.from}', to: '${s.to}' },`);
    // Each theme's light or dark half (builtin-themes.js PAIRS) and its own mode, for the Light / Dark / Auto switch.
    const pairs = BUILTIN_THEMES.filter((t) => t.pair).map((t) => `'${t.id}':'${t.pair}'`).join(',');
    const modes = BUILTIN_THEMES.map((t) => `'${t.id}':'${t.mode === 'light' ? 'light' : 'dark'}'`).join(',');
    return `${BEGIN}
    const THEME_KEYS = [${keys.map(q).join(',')}];
    const THEME_ROWS = {
${rows.join('\n')}
    };
    const THEMES = (function () {
        const out = {}, base = THEME_ROWS.vibe;
        for (const id in THEME_ROWS) {
            const row = THEME_ROWS[id], vars = {};
            for (let i = 0; i < THEME_KEYS.length; i++) { const v = row[i] || base[i]; if (v) vars[THEME_KEYS[i]] = v; }
            out[id] = vars;
        }
        return out;
    })();
    const SEASONS = [
${seasons.join('\n')}
    ];
    const PAIRS = { ${pairs} };
    const MODES = { ${modes} };
${END}`;
}

function currentBlock(src) {
    const a = src.indexOf(BEGIN);
    const b = src.indexOf(END);
    if (a >= 0 && b > a) return { a, b: b + END.length };
    // First run: the hand-written block.
    const start = src.indexOf('    const THEMES = {');
    if (start < 0) throw new Error('theme-loader.js: THEMES block not found');
    const close = src.indexOf('\n    };', start);
    return { a: start, b: close + '\n    };'.length };
}

const src = fs.readFileSync(LOADER, 'utf8');
const { a, b } = currentBlock(src);
const next = src.slice(0, a) + render() + src.slice(b);
const check = process.argv.includes('--check');
if (next === src) { if (!check) console.log('theme-loader.js is up to date'); process.exit(0); }
if (check) { console.error('theme-loader.js is stale: run node scripts/build-theme-loader.js'); process.exit(1); }
fs.writeFileSync(LOADER, next);
console.log(`theme-loader.js regenerated (${BUILTIN_THEMES.length} themes)`);
