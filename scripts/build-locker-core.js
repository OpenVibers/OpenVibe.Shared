#!/usr/bin/env node
'use strict';
/**
 * Writes ov-locker-core.js: openvibe-sdk/locker for the browser, as one classic script that sets window.OVLockerCore.
 * One implementation of the cryptography, not two: this copies the SDK's own src/locker files (WebCrypto only, no
 * dependency) into a tiny module table, records the SDK version and each file's SHA-256, and changes nothing in them
 * but the names of require and module (a browser file says neither).
 * test/ov-locker-core.test.js checks the file is current and runs the SDK's test vectors through it.
 *
 *   node scripts/build-locker-core.js [<path to openvibe-sdk>]     # default: node_modules/openvibe-sdk
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
// Every file in src/locker, in no particular order (the table resolves requires), except vectors.js, which stays in
// Node: a new file in the SDK is picked up by itself, so the browser build never lags the module.
const NODE_ONLY = new Set(['vectors']);
const filesOf = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith('.js')).map((f) => f.slice(0, -3)).filter((n) => !NODE_ONLY.has(n)).sort();

function build(sdkDir = path.join(ROOT, 'node_modules', 'openvibe-sdk')) {
    const dir = path.join(sdkDir, 'src', 'locker');
    const pkg = JSON.parse(fs.readFileSync(path.join(sdkDir, 'package.json'), 'utf8'));
    const parts = [];
    const hashes = [];
    for (const name of filesOf(dir)) {
        const file = path.join(dir, `${name}.js`);
        if (!fs.existsSync(file)) throw new Error(`openvibe-sdk ${pkg.version} has no src/locker/${name}.js`);
        const src = fs.readFileSync(file, 'utf8');
        const bad = [...src.matchAll(/require\((['"])([^'"]+)\1\)/g)].map((m) => m[2]).filter((r) => !/^\.\/[a-z]+$/.test(r));
        if (bad.length) throw new Error(`src/locker/${name}.js requires ${bad.join(', ')}: the browser build takes only ./locker files`);
        hashes.push(`${name}.js ${crypto.createHash('sha256').update(src).digest('hex').slice(0, 16)}`);
        // The one change: the files' require( and module.exports take the table's own names, so the browser file says neither.
        const body = src.replace(/\brequire\(/g, '__ovLockerReq(').replace(/\bmodule\.exports\b/g, '__ovLockerModule.exports');
        parts.push(`    ${JSON.stringify(name)}: function (__ovLockerModule, exports, __ovLockerReq) {\n${body}\n    },`);
    }
    return `/* Generated by scripts/build-locker-core.js from openvibe-sdk ${pkg.version} (src/locker). Do not edit: change the SDK,
 * release it, bump the pin, and run the script. The SDK's files, unchanged but for the names of require and module:
${hashes.map((h) => ` *   ${h}`).join('\n')}
 */
(function (root) {
    'use strict';
    if (!root || root.OVLockerCore) return;
    const defs = {
${parts.join('\n')}
    };
    const cache = {};
    function req(name) {
        const key = String(name).replace(/^\\.\\//, '');
        if (!defs[key]) throw new Error('ov-locker-core: no module ' + name);
        if (!cache[key]) { const m = { exports: {} }; cache[key] = m; defs[key](m, m.exports, req); }
        return cache[key].exports;
    }
    root.OVLockerCore = Object.assign({}, req('index'), { SDK_VERSION: ${JSON.stringify(pkg.version)} });
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
}

if (require.main === module) {
    const out = build(process.argv[2]);
    fs.writeFileSync(path.join(ROOT, 'ov-locker-core.js'), out);
    console.log(`ov-locker-core.js: ${out.length} bytes`);
}
module.exports = { build, filesOf, NODE_ONLY };
