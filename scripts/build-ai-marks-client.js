#!/usr/bin/env node
'use strict';
// A lazy browser copy of ai-marks-data for the Dock's model receipts. Source and attribution stay in ai-marks-data.js.
const fs = require('fs');
const path = require('path');
const data = require('../ai-marks-data');
const src = `/* Generated by scripts/build-ai-marks-client.js from ai-marks-data.js. */
(function (root) {
    'use strict';
    if (!root || root.OpenVibeAIMarks) return;
    const DATA = ${JSON.stringify(data)};
    const ALIAS = { openai: 'OpenAI', anthropic: 'Anthropic', google: 'Google', gemma: 'Gemma', meta: 'Meta', deepseek: 'DeepSeek', qwen: 'Qwen', mistral: 'Mistral', kimi: 'Kimi', glm: 'GLM', minimax: 'MiniMax', microsoft: 'Microsoft', xai: 'xAI', nvidia: 'NVIDIA', cohere: 'Cohere', perplexity: 'Perplexity' };
    const mark = (maker, model) => {
        const text = String(maker || model || '').toLowerCase();
        const key = Object.keys(ALIAS).find((name) => text.includes(name)) || (/gpt|\\bo[134]\\b/.test(text) ? 'openai' : /claude/.test(text) ? 'anthropic' : /gemini/.test(text) ? 'google' : /grok/.test(text) ? 'xai' : null);
        if (!key || !DATA[ALIAS[key]]) return null;
        const tile = document.createElement('span'); tile.className = 'ovdk-run-maker'; tile.setAttribute('role', 'img'); tile.setAttribute('aria-label', ALIAS[key]);
        tile.innerHTML = '<svg viewBox="0 0 24 24" aria-hidden="true">' + DATA[ALIAS[key]] + '</svg>';
        return tile;
    };
    root.OpenVibeAIMarks = { mark };
})(typeof window !== 'undefined' ? window : null);
`;
fs.writeFileSync(path.join(__dirname, '..', 'ai-marks-client.js'), src);
