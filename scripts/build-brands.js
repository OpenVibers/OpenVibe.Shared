#!/usr/bin/env node
'use strict';
/**
 * Writes brands.js: the brand logos the network shows (plan L54 K4: Font Awesome out), from Simple Icons (CC0-1.0,
 * https://simpleicons.org): the 24-unit path and the brand's colour, for every brand a Font Awesome `fa-brands` name on
 * an OpenVibe site points to. Brands Simple Icons does not carry (their owners asked for them to be removed: Microsoft,
 * Windows, LinkedIn, AWS) are left out, and those names stay with Font Awesome until the sites stop naming them.
 *
 *   node scripts/build-brands.js <path to an unpacked simple-icons package>   # writes brands.js
 */
const fs = require('fs');
const path = require('path');

// Font Awesome brand name (without fa-) → Simple Icons slug.
const FA = {
    youtube: 'youtube', 'square-youtube': 'youtube', twitch: 'twitch', discord: 'discord', github: 'github', 'square-github': 'github',
    'x-twitter': 'x', 'square-x-twitter': 'x', twitter: 'x', kick: 'kick', 'kickstarter-k': 'kick', kickstarter: 'kickstarter',
    google: 'google', tiktok: 'tiktok', threads: 'threads', spotify: 'spotify', soundcloud: 'soundcloud', reddit: 'reddit', 'reddit-alien': 'reddit',
    tumblr: 'tumblr', 'hacker-news': 'ycombinator', line: 'line',
    paypal: 'paypal', patreon: 'patreon', mastodon: 'mastodon', linux: 'linux', instagram: 'instagram', facebook: 'facebook', 'facebook-f': 'facebook',
    cloudflare: 'cloudflare', brave: 'brave', bluesky: 'bluesky', bitcoin: 'bitcoin', apple: 'apple', telegram: 'telegram', whatsapp: 'whatsapp',
    steam: 'steam', snapchat: 'snapchat', pinterest: 'pinterest', vimeo: 'vimeo', 'vimeo-v': 'vimeo', npm: 'npm', node: 'nodedotjs', 'node-js': 'nodedotjs',
    docker: 'docker', python: 'python', android: 'android', chrome: 'googlechrome', firefox: 'firefoxbrowser', 'firefox-browser': 'firefoxbrowser',
    gitlab: 'gitlab', ubuntu: 'ubuntu', raspberry: 'raspberrypi', 'raspberry-pi': 'raspberrypi', stripe: 'stripe', 'cc-stripe': 'stripe',
    signal: 'signal', matrix: 'matrix', medium: 'medium', wikipedia: 'wikipedia', 'wikipedia-w': 'wikipedia', openai: 'openai', ethereum: 'ethereum',
};

const pkg = process.argv[2];
if (!pkg) { console.error('usage: node scripts/build-brands.js <simple-icons package dir>'); process.exit(1); }
const meta = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8'));
const data = JSON.parse(fs.readFileSync(path.join(pkg, 'data', 'simple-icons.json'), 'utf8'));
const list = Array.isArray(data) ? data : data.icons;
const bySlug = new Map(list.map((i) => [i.slug, i]));
const brands = {};
const missing = [];
for (const slug of [...new Set(Object.values(FA))].sort()) {
    const file = path.join(pkg, 'icons', `${slug}.svg`);
    const info = bySlug.get(slug);
    if (!fs.existsSync(file) || !info) { missing.push(slug); continue; }
    const svg = fs.readFileSync(file, 'utf8');
    const d = (/<path d="([^"]+)"/.exec(svg) || [])[1];
    if (!d || !/^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$/.test(d)) { missing.push(slug); continue; }
    brands[slug] = { title: info.title, hex: `#${String(info.hex).toLowerCase()}`, path: d };
}
const fa = {};
for (const [name, slug] of Object.entries(FA)) if (brands[slug]) fa[name] = slug;
const out = `'use strict';
/* Generated by scripts/build-brands.js from simple-icons ${meta.version} (CC0-1.0, https://simpleicons.org). Do not edit. */
/**
 * openvibe-shared/brands — the brand logos OpenVibe shows, in place of Font Awesome's fa-brands (plan L54 K4):
 * ${Object.keys(brands).length} brands on a 24-unit grid, filled, each with its own colour. Brand names are their owners' marks; Simple Icons'
 * drawings are public domain.
 *
 *   brands.get('youtube') → { title, hex, path } or null
 *   brands.fromFa('fa-youtube') → 'youtube' (or null)
 *   brands.svg('youtube', { size, title, color })
 */
(function (root, factory) {
    const api = factory();
    if (typeof module === 'object' && module.exports) module.exports = api;
    else root.OVBrands = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
    const BRANDS = ${JSON.stringify(brands)};
    const FA = ${JSON.stringify(fa)};
    const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
    const get = (slug) => (has(BRANDS, slug) ? BRANDS[slug] : null);
    const fromFa = (name) => { const n = String(name || '').replace(/^fa-/, ''); return has(FA, n) ? FA[n] : null; };
    const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
    function svg(slug, { size = 24, title = '', color = 'currentColor' } = {}) {
        const b = get(slug);
        if (!b) return '';
        const label = title ? \` role="img" aria-label="\${esc(title)}"><title>\${esc(title)}</title>\` : ' aria-hidden="true">';
        return \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="\${Number(size) || 24}" height="\${Number(size) || 24}" fill="\${color === 'brand' ? b.hex : esc(color)}"\${label}<path d="\${b.path}"/></svg>\`;
    }
    return { BRANDS, FA, get, fromFa, svg, SLUGS: Object.keys(BRANDS) };
});
`;
fs.writeFileSync(path.join(__dirname, '..', 'brands.js'), out);
console.log(`brands.js: ${Object.keys(brands).length} brands for ${Object.keys(fa).length} Font Awesome names; not in Simple Icons: ${missing.join(', ') || 'none'}`);
