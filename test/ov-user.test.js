'use strict';
const assert = require('assert');
const { parseHTML } = require('linkedom');
const OVUser = require('../ov-user');
const { document, window } = parseHTML('<html><body><div id="host"></div></body></html>');
const host = document.getElementById('host');
const person = { username: 'Example', display_name: '<img src=x onerror=alert(1)>', avatar_url: 'https://openvibe.network/avatar/Example?s=160', profile_url: 'https://openvibe.network/@Example', channel_url: 'https://openvibe.live/@Example', level: 4, streak: 3, badges_count: 0, followers: 12, live: { now: true, site: 'live', url: 'https://openvibe.live/@Example' }, active_sites: [{ id: 'live', name: '<Live>', url: 'https://openvibe.live' }] };
const event = (type, extras = {}) => { const e = new window.Event(type, { bubbles: true, cancelable: true }); Object.assign(e, extras); return e; };
(async () => {
    let body = person, calls = [];
    const fetchImpl = async (url, options) => { calls.push({ url, options }); return { ok: true, json: async () => body }; };
    const mounted = OVUser.card(host, { username: '@Example', fetchImpl });
    await mounted.ready;
    assert.strictEqual(calls.length, 1);
    assert.strictEqual(calls[0].url, 'https://openvibe.network/api/v1/people/Example/card');
    assert.strictEqual(calls[0].options.credentials, 'omit');
    assert.strictEqual(calls[0].options.cache, 'no-store');
    assert.ok(host.textContent.includes('Level4Streak3 daysBadges0Followers12'));
    assert.ok(host.textContent.includes('Live now') && host.textContent.includes('<Live>'));
    assert.strictEqual(host.querySelectorAll('img').length, 1, 'display name is text, never markup');
    assert.strictEqual(host.querySelector('img').getAttribute('onerror'), null);
    assert.strictEqual(host.querySelectorAll('style').length, 0, 'plain kit markup only');
    body = { username: 'Example', profile_url: person.profile_url, level: null, streak: null, badges_count: null, followers: null, avatar_url: 'javascript:alert(1)', channel_url: 'javascript:alert(1)' };
    await mounted.refresh();
    for (const label of ['Level', 'Streak', 'Badges', 'Followers', 'Offline', 'Live now', 'This week']) assert.ok(!host.textContent.includes(label), label + ' stays absent');
    assert.strictEqual(host.querySelector('img'), null);
    assert.strictEqual(host.querySelector('dl'), null);
    assert.strictEqual(host.querySelectorAll('a').length, 1, 'unsafe links omitted');
    mounted.destroy(); assert.strictEqual(host.childNodes.length, 0);
    assert.throws(() => OVUser.card(host, { username: '../bad' }), TypeError);

    let resolveOld, oldSignal;
    const old = OVUser.card(host, { username: 'OldName', fetchImpl: (_url, options) => { oldSignal = options.signal; return new Promise(resolve => { resolveOld = resolve; }); } });
    await Promise.resolve();
    body = { username: 'NewName', profile_url: 'https://openvibe.network/@NewName' };
    const newer = OVUser.card(host, { username: 'NewName', fetchImpl });
    await newer.ready;
    assert.ok(oldSignal.aborted);
    resolveOld({ ok: true, json: async () => person }); await old.ready;
    assert.ok(host.textContent.includes('@NewName') && !host.textContent.includes('@Example'), 'late response cannot replace a newer mount');
    newer.destroy();
    const unavailable = OVUser.card(host, { username: 'Example', fetchImpl: async () => ({ ok: false, status: 503 }) });
    assert.strictEqual(await unavailable.ready, null);
    assert.ok(host.textContent.includes('Profile unavailable.') && host.querySelector('a').href === person.profile_url);
    unavailable.destroy();

    const mention = document.createElement('a'); mention.href = person.profile_url; mention.textContent = '@Example'; document.body.appendChild(mention);
    const avatar = document.createElement('button'); avatar.setAttribute('data-ov-user', 'Example'); avatar.appendChild(document.createElement('img')); document.body.appendChild(avatar);
    const marked = document.createElement('span'); marked.setAttribute('data-username', 'Example'); marked.setAttribute('role', 'button'); marked.tabIndex = 0; document.body.appendChild(marked);
    const foreign = document.createElement('a'); foreign.href = 'https://example.org/@Example'; document.body.appendChild(foreign);
    const opened = [];
    let unbind = OVUser.bind(document, { onOpen: value => opened.push(value.username) });
    mention.dispatchEvent(event('click')); avatar.firstChild.dispatchEvent(event('click')); marked.dispatchEvent(event('keydown', { key: 'Enter' }));
    assert.deepStrictEqual(opened, ['Example', 'Example', 'Example']);
    mention.dispatchEvent(event('click', { ctrlKey: true })); foreign.dispatchEvent(event('click'));
    assert.strictEqual(opened.length, 3, 'modified and foreign links keep their native behavior');
    body = person;
    const inCard = OVUser.card(host, { username: 'Example', fetchImpl }); await inCard.ready;
    host.querySelector('a').dispatchEvent(event('click'));
    assert.strictEqual(opened.length, 3, 'links inside the card remain navigation');
    inCard.destroy();
    unbind = OVUser.bind(document, { onOpen: value => opened.push(value.username) });
    mention.dispatchEvent(event('click')); assert.strictEqual(opened.length, 4, 'rebinding does not duplicate listeners');
    unbind(); mention.dispatchEvent(event('click')); assert.strictEqual(opened.length, 4);

    // Native dialog opening/closing and request disposal through the default hook.
    const create = document.createElement.bind(document);
    document.createElement = name => { const el = create(name); if (name === 'dialog') el.showModal = () => el.setAttribute('open', ''); return el; };
    unbind = OVUser.bind(document, { fetchImpl });
    mention.dispatchEvent(event('click'));
    await new Promise(resolve => setImmediate(resolve));
    const dialog = document.querySelector('dialog');
    assert.ok(dialog?.hasAttribute('open'));
    assert.ok(dialog.textContent.includes('@Example'));
    dialog.querySelector('button').dispatchEvent(event('click'));
    assert.strictEqual(document.querySelector('dialog'), null);
    unbind();
    assert.ok(require('../files').BROWSER.includes('ov-user.js'));
    assert.strictEqual(require('../package.json').exports['./ov-user'], './ov-user.js');
    console.log('ov-user: single read, safe kit markup, absent fields, cancellation, stale-response protection, mention/avatar/keyboard hooks and dialog lifecycle passed');
})().catch(e => { console.error(e); process.exitCode = 1; });
