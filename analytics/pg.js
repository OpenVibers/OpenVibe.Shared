'use strict';
/**
 * Request analytics on PostgreSQL (ADR-035; ADR-021's privacy bounds unchanged). The same tracker, tables and
 * getStats/getOverview/getBotAnalysis shapes on an openvibe-sdk/db handle:
 *
 *   const { AnalyticsTrackerPg, analyticsSchema } = require('openvibe-shared/analytics/pg');
 *   // migrations/NNNN_analytics.sql holds analyticsSchema()
 *   const tracker = new AnalyticsTrackerPg(db, 'network', { paramPrefixes: [...] });
 *   app.use(tracker.middleware());
 *   await tracker.flush(); await tracker.aggregate(); await tracker.getStats({ days: 7 });
 *
 * PostgreSQL request handling:
 *  - the request path never waits for the database: record() buffers the row in memory, and flush() (every
 *    5 s, and at 100 rows) writes the buffer in one transaction;
 *  - uniques across processes: the visitor hash needs the day's salt that every process of the service shares
 *    (analytics_day_salts), which is async now. So record() keeps (ip, user agent) for the visitor only until the
 *    next flush, in memory, like the rate counters always did; flush() reads or creates the day's salt, hashes,
 *    and writes the hash. The IP never reaches the database;
 *  - session ids are per process (as they always were: the session map was in memory), from a process-local
 *    daily key, so record() stays synchronous;
 *  - reads and rollups are async; SUM() over bigint comes back as numeric (exact), so every sum is cast.
 */
const crypto = require('crypto');
const { AnalyticsTrackerCore, sqlTime, dayOf, hourOf } = require('./core');
const privacy = require('./privacy');

const MAX_BUFFER = 5000;
const MAX_BOT_API_KEYS = 1000;   // 1000 rows x 6 values stays one INSERT; beyond it a call keeps its raw row
const DAY = 86400000;

/** The status class of a code, the same grouping getStats's statusCodes uses. */
function statusClassOf(code) {
    const n = Number(code);
    if (n >= 200 && n < 300) return '2xx';
    if (n >= 300 && n < 400) return '3xx';
    if (n >= 400 && n < 500) return '4xx';
    if (n >= 500) return '5xx';
    return 'other';
}

/** The first three path segments of a route template (/api/v1/streams for /api/v1/streams/:id), or two otherwise. */
function endpointGroupOf(path) {
    const parts = String(path || '').split('/').filter(Boolean);
    const n = parts[0] === 'api' || parts[0] === 'internal' || parts[0] === 'oauth' ? 3 : 2;
    return `/${parts.slice(0, n).join('/')}` || '/';
}

/**
 * The bot family the admin's breakdown groups by: the tracker's bot_type (known_crawler, no_useragent,
 * rate_limit, honeypot_hit). The user-agent class stays on the raw row; it is not carried per counter.
 */
function botFamilyOf(botType) {
    const s = String(botType || 'unknown');
    return /^[a-z0-9_]{1,32}$/.test(s) ? s : 'unknown';
}

